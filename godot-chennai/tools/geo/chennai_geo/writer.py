INFRA_FILE = "infra.bin"
DETAIL_FILE = "detail.bin"

ATTRIBUTION = "© OpenStreetMap contributors"


def _tile_dir(tc: int, tr: int) -> str:
    return f"tiles/{tc}_{tr}"


def _simplify_ring(pts: list[tuple[float, float]], tol: float) -> list[tuple[float, float]]:
    if len(pts) < 8:
        return pts
    s = Polygon(pts).exterior.simplify(tol, preserve_topology=True)
    out = [(round(x, 2), round(z, 2)) for x, z in list(s.coords)[:-1]]
    return out if len(out) >= 3 else pts


ATTRIBUTION_MD = """# World data: attribution and licence

Map data © OpenStreetMap contributors, available under the Open Database Licence (ODbL) 1.0:
https://www.openstreetmap.org/copyright

{sources}
- The files in this folder are a Derived Database of OpenStreetMap under the ODbL. The way to
  rebuild them is offered with them: `tools/geo/` (the build scripts), `data/MANIFEST.json` (the
  dataset), `data/boundary/world-boundary.geojson` (the clip boundary, itself derived from the
  OSM Tamil Nadu relation), and `docs/world-format.md`.
- The game shows "© OpenStreetMap contributors" wherever the map is shown (a Produced Work).
- Invented, not from OSM, and called estimated: heights where `heightFrom` is not `height` or
  `levels`, road widths where `widthFrom` is `class`, wall colours, generated trees, landmark
  heights and footprints listed in each landmark's `estimated`.
- No other dataset is in these files yet. When Overture buildings (ODbL) or Google Open Buildings
  (chosen under ODbL, blueprint §21) are fused in, they are credited here.

(Generated by `tools/geo` with the world.)
"""


def _attribution(source: dict[str, Any], data_date: str) -> str:
    lines = []
    for d in source.get("datasets", []):
        lines.append(f"- Source: `{d.get('url')}`, OSM data timestamp **{d.get('osmDataTimestamp')}**, downloaded "
                     f"{str(d.get('downloaded', ''))[:10]}, sha256 `{d.get('sha256')}` (`data/MANIFEST.json`).")
    if not lines:
        lines.append(f"- OSM data timestamp **{data_date}**.")
    return ATTRIBUTION_MD.format(sources="\n".join(lines))


def write_world_v2(w: World, out: Path, source: dict[str, Any] | None = None, name: str = "Chennai") -> dict[str, Any]:
    """Write `out/world.json` and `out/tiles/<tc>_<tr>/{tile.json,roads.bin,areas.bin,c/*.bin}`.
    Returns size statistics (bytes per tile and per ring)."""
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    g = w.grid
    tiles: dict[tuple[int, int], dict[str, Any]] = {}

    def tile(tc: int, tr: int) -> dict[str, Any]:
        if (tc, tr) not in tiles:
            tiles[(tc, tr)] = {"chunks": [], "pois": [], "busStops": [], "signals": [], "districts": [], "settlements": [], "aeroways": [],
                               "areas": [], "bytes": 0, "ring_bytes": Counter()}
        return tiles[(tc, tr)]

    def tile_xz(x: float, z: float) -> tuple[int, int]:
        return tile_of(g.col(x), g.row(z))

    ring_bytes: Counter[int] = Counter()
    blobs: dict[tuple[int, int], list[tuple[int, int, int, bytes]]] = {}
    for (col, row), c in sorted(w.chunks.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        data = codec_v2.encode_chunk(ChunkV2(col, row, c.ring, c.buildings, c.trees, c.areas), g.centre(col, row))
        tc, tr = tile_of(col, row)
        blobs.setdefault((tc, tr), []).append((col, row, c.ring, data))
        tile(tc, tr)
        ring_bytes[c.ring] += len(data)
    # Road-only squares are listed with size 0 (as today), so the game knows to draw road there.
    for col, row in sorted(w.road_chunk_keys - set(w.chunks), key=lambda k: (k[1], k[0])):
        tile(*tile_of(col, row))["chunks"].append([col, row, 0, 0, w.road_chunk_rings.get((col, row), w.max_ring)])
    for p in w.pois:
        tile(*tile_xz(p["x"], p["z"]))["pois"].append(named_poi(p))
    for key, items in (("busStops", w.bus_stops), ("signals", w.signals), ("districts", w.districts), ("settlements", w.settlements)):
        for p in items:
            tile(*tile_xz(p["x"], p["z"]))[key].append(p)
    for aw in w.aeroways:
        ac = centroid(aw.points)
        tile(*tile_xz(*ac))["aeroways"].append({
            "id": aw.id, "kind": aw.kind, "source": aw.source.label(), "closed": aw.closed,
            **({"ref": aw.ref} if aw.ref else {}), **({"name": aw.name} if aw.name else {}),
            **({"width": aw.width} if aw.width else {}), **({"surface": aw.surface} if aw.surface else {}),
            "points": [[x, z] for x, z in aw.points],
        })
    for ar in w.areas:
        rc = centroid(ar.outline)
        tile(*tile_xz(*rc))["areas"].append(Area(ar.id, ar.kind, _simplify_ring(ar.outline, 1.0), ar.name, [_simplify_ring(h, 1.0) for h in ar.holes], ar.source))
    pieces = codec_v2.road_pieces_by_tile(w.roads, tile_xz)
    for pkey in pieces:
        tile(*pkey)
    infra_ways = infra.waterway_pieces_by_tile(w.infra.waterways, tile_xz) if w.infra else {}
    infra_spots: dict[tuple[int, int], list[infra.Spot]] = {}
    if w.infra:
        for sp in w.infra.spots:
            infra_spots.setdefault(tile_xz(sp.x, sp.z), []).append(sp)
    # Format 2.2: detail records by tile (positions by tile of the point, lines cut at tile edges).
    dt: dict[tuple[int, int], dict[str, list[Any]]] = {}
    detail_stats: dict[tuple[int, int], Counter[str]] = {}
    if w.detail is not None:
        dd = w.detail

        def bucket(key: tuple[int, int]) -> dict[str, list[Any]]:
            if key not in dt:
                dt[key] = {"buildings": [], "parts": [], "objects": [], "lines": [], "zones": [], "signs": []}
                detail_stats[key] = Counter()
            return dt[key]

        for bd in dd.buildings:
            bucket(tile_xz(*dd.building_points[bd.id]))["buildings"].append(bd)
        for pt in dd.parts:
            bucket(tile_xz(*centroid(pt.outline)))["parts"].append(pt)
        for ob in dd.objects:
            bucket(tile_xz(ob.x, ob.z))["objects"].append(ob)
        for zo in dd.zones:
            bucket(tile_xz(*centroid(zo.outline)))["zones"].append(zo)
        for sg in dd.signs:
            bucket(tile_xz(sg.x, sg.z))["signs"].append(sg)

        def tile_rects(b: Bounds) -> list[tuple[tuple[int, int], Bounds]]:
            out_: list[tuple[tuple[int, int], Bounds]] = []
            for tcx in range(math.floor((b.min_x - g.min_x) / TILE_SIZE), math.floor((b.max_x - g.min_x) / TILE_SIZE) + 1):
                for trz in range(math.floor((b.min_z - g.min_z) / TILE_SIZE), math.floor((b.max_z - g.min_z) / TILE_SIZE) + 1):
                    x0, z0 = g.min_x + tcx * TILE_SIZE, g.min_z + trz * TILE_SIZE
                    out_.append(((tcx, trz), Bounds(x0, x0 + TILE_SIZE, z0, z0 + TILE_SIZE)))
            return out_

        for dkey, ls in detail_mod.lines_by_tile(dd.lines, tile_rects).items():
            bucket(dkey)["lines"].extend(ls)
        for dkey, rec in dt.items():
            s = detail_stats[dkey]
            s["part"] = len(rec["parts"])
            for ob in rec["objects"]:
                s[f"object:{ob.kind}"] += 1
            for li in rec["lines"]:
                s[f"line:{li.kind}:length-m"] += int(sum(math.dist(a, b2) for a, b2 in zip(li.points, li.points[1:])))
            for zo in rec["zones"]:
                s[f"zone:{zo.kind}"] += 1
            for sg in rec["signs"]:
                s[f"sign:{sg.category}"] += 1
        for ckey, ch in w.chunks.items():
            tkey = tile_of(*ckey)
            if tkey in detail_stats:
                detail_stats[tkey]["building"] += len(ch.buildings)
    infra_bytes = 0
    detail_bytes = 0
    tile_rows = []
    tile_overhead: Counter[int] = Counter()
    for (tc, tr), t in sorted(tiles.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        d = out / _tile_dir(tc, tr)
        d.mkdir(parents=True, exist_ok=True)
        pack, entries = codec_v2.encode_pack((tc, tr), blobs.get((tc, tr), []))
        (d / "chunks.bin").write_bytes(pack)
        t["chunks"].extend(entries)
        t["bytes"] += len(pack)
        names = StringTable()
        roads_bytes = codec_v2.encode_roads((tc, tr), pieces.get((tc, tr), []), names)
        (d / "roads.bin").write_bytes(roads_bytes)
        areas_bytes = codec_v2.encode_areas((tc, tr), t["areas"])
        (d / "areas.bin").write_bytes(areas_bytes)
        if w.infra is not None:
            decks = []
            for i, pc in enumerate(pieces.get((tc, tr), [])):
                prof = w.infra.profiles.get(pc.road.id)
                if prof is None:
                    continue
                hs = infra.piece_samples(prof, pc.offset, pc.road.points)
                if max(hs) > 0.005:
                    decks.append((i, hs))
            blob = infra.encode_infra((tc, tr), decks, infra_ways.get((tc, tr), []), infra_spots.get((tc, tr), []))
            (d / INFRA_FILE).write_bytes(blob)
            infra_bytes += len(blob)
        if w.detail is not None:
            rec = dt.get((tc, tr), {"buildings": [], "parts": [], "objects": [], "lines": [], "zones": [], "signs": []})
            blob = detail_mod.encode_detail((tc, tr), rec["buildings"], rec["parts"], rec["objects"], rec["lines"], rec["zones"], rec["signs"])
            (d / DETAIL_FILE).write_bytes(blob)
            detail_bytes += len(blob)
        min_x = g.min_x + tc * TILE_SIZE
        min_z = g.min_z + tr * TILE_SIZE
        rings_here = sorted({c[4] for c in t["chunks"]}) or [w.max_ring]
        tj = {
            "format": codec_v2.FORMAT,
            "tile": [tc, tr],
            "bounds": {"minX": min_x, "maxX": min_x + TILE_SIZE, "minZ": min_z, "maxZ": min_z + TILE_SIZE},
            "rings": rings_here,
            "chunkPack": "chunks.bin",
            "chunks": sorted(t["chunks"], key=lambda c: (c[1], c[0])),
            "roads": "roads.bin",
            "roadPieces": len(pieces.get((tc, tr), [])),
            "roadNames": names.items,
            "areas": "areas.bin",
            "pois": t["pois"],
            "busStops": t["busStops"],
            "signals": t["signals"],
            "districts": t["districts"],
            "settlements": t["settlements"],
            "aeroways": t["aeroways"],
        }
        text = json.dumps(tj, separators=(",", ":"), ensure_ascii=False)
        (d / "tile.json").write_text(text)
        extra = len(roads_bytes) + len(areas_bytes) + len(text.encode())
        t["bytes"] += extra
        tile_overhead[min(rings_here)] += extra
        tile_rows.append([tc, tr, len([c for c in t["chunks"] if c[3] > 0]), t["bytes"], min(rings_here)])
    r0 = w.grid.legacy_offset
    boundary = w.playable.shape()
    if isinstance(boundary, Polygon):
        bpts = [[round(x, 1), round(z, 1)] for x, z in boundary.simplify(5).exterior.coords][:-1]
    else:  # pragma: no cover
        bpts = []
    rect = w.playable.rect
    index = {
        "format": codec_v2.FORMAT,
        "name": name,
        "origin": {"lat": ANNA_NAGAR_ORIGIN.lat, "lng": ANNA_NAGAR_ORIGIN.lng},
        "projection": {"type": "equirectangular", "earthRadius": EARTH_RADIUS, "axes": "+X east, +Y up, -Z north; metres", "cosLatAtOrigin": True},
        "attribution": ATTRIBUTION,
        "licence": "ODbL 1.0 (https://www.openstreetmap.org/copyright)",
        "dataDate": w.data_date,
        "source": source or {},
        "chunkSize": CHUNK_SIZE,
        "tileChunks": TILE_CHUNKS,
        "tileSize": TILE_SIZE,
        "grid": {"minX": g.min_x, "minZ": g.min_z, "cols": g.cols, "rows": g.rows},
        "bounds": {"minX": rect.min_x, "maxX": rect.max_x, "minZ": rect.min_z, "maxZ": rect.max_z},
        "boundary": bpts,
        "maxRing": w.max_ring,
        "rings": [{"id": r.id, "name": r.name, "box": {"south": r.box[0], "west": r.box[1], "north": r.box[2], "east": r.box[3]}, "built": r.id <= w.max_ring} for r in RINGS],
        "legacy": {"note": "today's c/<c>_<r>.bin is this grid's chunk (c + colOffset, r + rowOffset)", "colOffset": r0[0], "rowOffset": r0[1]},
        "datasets": DATASETS,
        "tiles": tile_rows,
        "landmarks": w.landmarks,
        **({"sea": w.sea} if w.sea else {}),
        **({"minor": detail_mod.MINOR if w.detail is not None else infra.MINOR, "infra": {"file": INFRA_FILE, "deckStep": infra.STEP, "note": "format 2.1: road heights (estimated), waterways, street spots; world-format.md 3.7"}} if w.infra else {}),
        **({"detail": {"file": DETAIL_FILE, "categories": "assets/city/sign_categories.json", "note": "format 2.2: building colours, materials and parts, street objects, barriers, zones, sign categories; world-format.md 3.8"}} if w.detail is not None else {}),
    }
    text = json.dumps(index, separators=(",", ":"), ensure_ascii=False)
    (out / "world.json").write_text(text)
    (out / "ATTRIBUTION.md").write_text(_attribution(source or {}, w.data_date))
    if w.detail is not None:
        cat_keys = {c.id: c.key for c in detail_mod.load_categories().items}
        per_tile = {k: Counter({(f"sign:{cat_keys[int(x.split(':')[1])]}" if x.startswith("sign:") and x != "sign:public-name" else x): v for x, v in c.items()}) for k, c in detail_stats.items()}
        (out / "DETAIL.md").write_text(detail_mod.coverage_markdown(w.detail.stats, per_tile, f"OSM data {w.data_date} (© OpenStreetMap contributors, ODbL 1.0). Generated by `tools/geo` with the world; `docs/osm-detail.md` explains it."))
    total = sum(f.stat().st_size for f in out.rglob("*") if f.is_file())
    return {"total": total, "chunk_bytes_by_ring": dict(sorted(ring_bytes.items())), "tile_files_by_first_ring": dict(sorted(tile_overhead.items())),
            "world_json": len(text.encode()), "tiles": len(tile_rows), "infra_bytes": infra_bytes, "detail_bytes": detail_bytes, "files": sum(1 for f in out.rglob("*") if f.is_file())}


def write_world_v1(w: World, out: Path) -> dict[str, int]:
    """Today's format from a ring-0 world: index.json, roads.bin, c/<c>_<r>.bin with today's chunk
    numbering and only the v1 content (v1 road classes, v1 area kinds, way buildings)."""
    from .enums import V1_AREA_KINDS  # noqa: PLC0415
    from .rules import V1_ROAD_CLASS  # noqa: PLC0415

    if w.max_ring != 0:
        raise ValueError("Format 1 has one rectangle: write it from a ring-0 build.")
    if out.exists():
        shutil.rmtree(out)
    (out / "c").mkdir(parents=True)
    dc, dr = w.grid.legacy_offset
    b: Bounds = w.playable.rect
    sizes: dict[tuple[int, int], int] = {}
    for (col, row), c in sorted(w.chunks.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        lc, lr = col - dc, row - dr
        blds = [x for x in c.buildings if not x.id & 0x80000000]
        areas = [a for a in c.areas if a.kind in V1_AREA_KINDS and not a.holes]
        if not blds and not c.trees and not areas:
            continue
        data = codec_v1.encode_chunk(lc, lr, blds, c.trees, areas, b, CHUNK_SIZE)
        (out / codec_v1.chunk_file(lc, lr)).write_bytes(data)
        sizes[(lc, lr)] = len(data)
    roads = [r for r in w.roads if r.highway in V1_ROAD_CLASS]
    for col, row in w.road_chunk_keys:
        sizes.setdefault((col - dc, row - dr), 0)
    rb, names = codec_v1.encode_roads(roads)
    (out / "roads.bin").write_bytes(rb)
    index = {
        "format": 1, "name": "Chennai", "origin": {"lat": ANNA_NAGAR_ORIGIN.lat, "lng": ANNA_NAGAR_ORIGIN.lng}, "attribution": ATTRIBUTION,
        "dataDate": w.data_date, "bounds": b.to_json(), "chunkSize": CHUNK_SIZE,
        "chunks": [[c, r, s] for (c, r), s in sorted(sizes.items(), key=lambda kv: (kv[0][1], kv[0][0]))],
        "roads": "roads.bin", "roadNames": names,
        "areas": [{"id": a.id, "kind": a.kind, **({"name": a.name} if a.name else {}), "outline": [{"x": x, "z": z} for x, z in a.outline]}
                  for a in w.areas if a.kind in V1_AREA_KINDS and a.source and a.source.dataset == 0],
        "pois": [named_poi(p) for p in w.pois], "landmarks": w.landmarks, "busStops": w.bus_stops, "signals": w.signals,
        "districts": w.districts, **({"sea": w.sea} if w.sea else {}),
    }
    (out / "index.json").write_text(json.dumps(index, separators=(",", ":"), ensure_ascii=False))
    return {"chunks": len([s for s in sizes.values() if s]), "roads": len(roads)}


def read_world_v2(root: Path) -> dict[str, Any]:
    """Decode a written world (for reports and tests): world.json plus every tile."""
    index = json.loads((root / "world.json").read_text())
    g = index["grid"]
    size = index["chunkSize"]

    def centre(col: int, row: int) -> tuple[float, float]:
        return (g["minX"] + (col + 0.5) * size, g["minZ"] + (row + 0.5) * size)

    tiles = []
    for tc, tr, *_ in index["tiles"]:
        d = root / _tile_dir(tc, tr)
        tj = json.loads((d / "tile.json").read_text())
        pack = (d / tj["chunkPack"]).read_bytes()
        codec_v2.check_pack(pack, tj["chunks"])
        chunks = [codec_v2.decode_chunk(pack[off : off + n], centre) for c, r, off, n, _ring in tj["chunks"] if n > 0]
        roads = codec_v2.decode_roads((d / "roads.bin").read_bytes(), tj["roadNames"])
        areas = codec_v2.decode_areas((d / "areas.bin").read_bytes())
        tiles.append({"tile": (tc, tr), "json": tj, "chunks": chunks, "roads": roads, "areas": areas})
    return {"index": index, "tiles": tiles}
