"""Coverage report: one markdown file per region tile plus a summary (world/REPORT.md)."""
from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from .geometry import centroid
from .regions import RINGS, tile_of
from .world import World

ROAD_TAGS = ("width", "lanes", "surface", "bridge", "layer", "maxspeed", "name")


def _pct(n: int, d: int) -> str:
    return f"{n:,} ({100 * n / d:.1f} %)" if d else "0"


def _stats(w: World, keep: Any) -> dict[str, Any]:
    b_count = 0
    height: Counter[str] = Counter()
    roof: Counter[str] = Counter()
    use: Counter[str] = Counter()
    holes = merged = repaired = rel = 0
    for c in w.chunks.values():
        if not keep(c.col, c.row):
            continue
        for b in c.buildings:
            b_count += 1
            height[b.height_from] += 1
            roof[b.roof_shape] += 1
            use[b.use] += 1
            holes += bool(b.holes)
            merged += bool(b.merged)
            rel += bool(b.id & 0x80000000)
    roads = [r for r in w.roads if keep(w.grid.col(r.points[0][0]), w.grid.row(r.points[0][1]))]
    kinds = Counter(r.kind for r in roads)
    tags = {
        "width": sum(r.width_from == "width" for r in roads),
        "lanes": sum(r.lanes is not None for r in roads),
        "surface": sum(bool(r.surface) for r in roads),
        "bridge": sum(r.bridge for r in roads),
        "tunnel": sum(r.tunnel for r in roads),
        "layer": sum(r.layer != 0 for r in roads),
        "maxspeed": sum(r.maxspeed > 0 for r in roads),
        "name": sum(bool(r.name) for r in roads),
    }
    chunks = [c for c in w.chunks.values() if keep(c.col, c.row)]
    road_only = [k for k in w.road_chunk_keys - set(w.chunks) if keep(*k)]
    no_buildings = sum(1 for c in chunks if not c.buildings)
    areas = Counter(a.kind for a in w.areas if keep(w.grid.col(centroid(a.outline)[0]), w.grid.row(centroid(a.outline)[1])))
    aero = Counter(a.kind for a in w.aeroways if keep(w.grid.col(centroid(a.points)[0]), w.grid.row(centroid(a.points)[1])))
    trees = Counter(t.source for c in chunks for t in c.trees)
    return {"buildings": b_count, "height": height, "roof": roof, "use": use, "holes": holes, "merged": merged, "relation_parts": rel,
            "roads": len(roads), "kinds": kinds, "tags": tags, "chunks": len(chunks), "road_only": len(road_only), "no_buildings": no_buildings,
            "areas": areas, "aero": aero, "trees": trees}


def _section(s: dict[str, Any]) -> list[str]:
    n = s["buildings"]
    lines = [
        f"- Chunks with a file: {s['chunks']:,}; road-only squares (no file): {s['road_only']:,}; chunks with no building: {s['no_buildings']:,}",
        f"- Buildings: {n:,} (multipolygon parts {s['relation_parts']:,}, with courtyards/holes {s['holes']:,}, fused from other datasets {s['merged']:,})",
        "- Height source: " + ", ".join(f"{k} {_pct(v, n)}" for k, v in s["height"].most_common()),
        "- Roof shape tagged: " + _pct(n - s["roof"].get("unknown", 0), n) + ("; " + ", ".join(f"{k} {v}" for k, v in s["roof"].most_common() if k != "unknown") if len(s["roof"]) > 1 else ""),
        "- Building use: " + ", ".join(f"{k} {v:,}" for k, v in s["use"].most_common(8)),
        f"- Roads: {s['roads']:,}: " + ", ".join(f"{k} {v:,}" for k, v in s["kinds"].most_common()),
        "- Road tags: " + ", ".join(f"{k} {_pct(v, s['roads'])}" for k, v in s["tags"].items()),
        "- Areas: " + (", ".join(f"{k} {v:,}" for k, v in s["areas"].most_common()) or "none"),
        "- Trees: " + (", ".join(f"{k} {v:,}" for k, v in s["trees"].most_common()) or "none"),
        "- Airport features: " + (", ".join(f"{k} {v}" for k, v in s["aero"].most_common()) or "none"),
    ]
    return lines


def write_reports(w: World, out: Path, sizes: dict[str, Any], header: str) -> str:
    (out / "reports").mkdir(parents=True, exist_ok=True)
    tiles: dict[tuple[int, int], int] = defaultdict(int)
    for k in [*w.chunks, *w.road_chunk_keys]:
        tiles[tile_of(*k)] += 1
    ring_of = {k: c.ring for k, c in w.chunks.items()} | w.road_chunk_rings
    summary = [f"# World coverage report", "", header, "",
               f"Generated by `tools/geo` (`cli.py build`). Total {sizes['total'] / 1048576:.1f} MB in {sizes['files']} files, {sizes['tiles']} region tiles.", ""]
    summary += ["## Whole world (rings 0.." + str(w.max_ring) + ")", "", *_section(_stats(w, lambda c, r: True)), ""]
    fixed = {k: v for k, v in w.stats.items() if ":" in k}
    summary += ["- Geometry: " + (", ".join(f"{k} {v:,}" for k, v in sorted(fixed.items())) or "nothing repaired or dropped"), ""]
    summary += ["## By ring", "", "| Ring | What | Chunk bytes | Buildings | Roads (by first point) |", "|---|---|---|---|---|"]
    for r in RINGS[: w.max_ring + 1]:
        s = _stats(w, lambda c, rr, r=r: ring_of.get((c, rr), w.max_ring) == r.id)
        summary.append(f"| {r.id} | {r.name} | {sizes['chunk_bytes_by_ring'].get(r.id, 0) / 1048576:.2f} MB | {s['buildings']:,} | {s['roads']:,} |")
    summary += ["", "Tile files (tile.json, roads.bin, areas.bin) by the first ring in the tile: "
                + ", ".join(f"ring {k} {v / 1048576:.2f} MB" for k, v in sizes["tile_files_by_first_ring"].items()) + f"; world.json {sizes['world_json'] / 1024:.0f} KB.", ""]
    summary += ["## Tiles", "", "| Tile | Squares | Report |", "|---|---|---|"]
    for (tc, tr) in sorted(tiles, key=lambda k: (k[1], k[0])):
        s = _stats(w, lambda c, rr, t=(tc, tr): tile_of(c, rr) == t)
        md = [f"# Tile {tc}_{tr}", "", header, "", *_section(s), ""]
        (out / "reports" / f"{tc}_{tr}.md").write_text("\n".join(md))
        summary.append(f"| {tc}_{tr} | {tiles[(tc, tr)]} | [reports/{tc}_{tr}.md](reports/{tc}_{tr}.md) |")
    text = "\n".join(summary) + "\n"
    (out / "REPORT.md").write_text(text)
    return text
