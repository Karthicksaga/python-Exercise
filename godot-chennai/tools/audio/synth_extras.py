def rail_announce():
    """A three-note station chime, falling then rising ("ding-dong-ding"), bell partials."""
    out = np.zeros(int(2.0 * RATE))
    for start, hz in ((0.0, 880.0), (0.55, 698.5), (1.1, 783.99)):
        t = np.arange(int(1.2 * RATE)) / RATE
        note = sum(a * np.sin(2 * np.pi * hz * r * t) * np.exp(-t / d)
                   for r, a, d in ((1, 1.0, 0.45), (2.0, 0.35, 0.25), (2.76, 0.2, 0.15), (5.4, 0.08, 0.06)))
        i = int(start * RATE)
        seg = (note * np.minimum(1.0, t / 0.003))[:len(out) - i]
        out[i:i + len(seg)] += seg
    return fade(out, 0.002, 0.2)


def rail_squeal():
    """Brake squeal: a thin, wobbling 3 kHz note and its octave over a little noise. Every
    frequency is a whole number of cycles per loop, so the wrap is exact."""
    L = 2.0
    t = t_axis(L)
    phase = 2 * np.pi * 3000.0 * t + 80.0 * np.sin(2 * np.pi * 1.5 * t)
    x = np.sin(phase) + 0.45 * np.sin(2 * phase + 0.7) + 0.2 * np.sin(1.5 * phase)
    x *= 0.65 + 0.35 * np.sin(2 * np.pi * 7.0 * t + 1.0)
    x += 0.35 * periodic_noise(L, 2000, 6500, 0.0, seed=7)
    return x


def rail_clatter():
    """Wheels over rail joints at about 20 m/s: pairs of axle hits, four pairs a second and a half."""
    L = 3.0
    buf = np.zeros(int(L * RATE))
    rng = np.random.default_rng(11)
    pair = 0.75
    for k in range(int(L / pair)):
        for j, off in enumerate((0.0, 0.125, 0.31, 0.435)):
            amp = (1.0 if j % 2 == 0 else 0.7) * rng.uniform(0.8, 1.1)
            hit = resonant_hit([180, 640, 1500, 2700], [0.05, 0.03, 0.018, 0.01], [1.0, 0.7, 0.5, 0.3], seed=int(rng.integers(1000)))
            circular_add(buf, int((k * pair + off) * RATE), hit * amp)
    return buf + 0.08 * periodic_noise(L, 200, 2500, 0.0, seed=3) * np.abs(buf).max()


def rail_rumble():
    """The roll and motor drone of a train: low noise with a 100 Hz hum, periodic over 4 s."""
    L = 4.0
    t = t_axis(L)
    x = periodic_noise(L, 25, 450, 1.0, seed=5)
    hum = 0.35 * np.sin(2 * np.pi * 100 * t) + 0.18 * np.sin(2 * np.pi * 200 * t + 1.0)
    swell = 1.0 + 0.2 * np.sin(2 * np.pi * 0.5 * t)
    return (x + hum) * swell


def bus_airbrake():
    """Compressed air let out: a sharp burst of hiss that dies away, and a short tail."""
    L = 1.3
    t = t_axis(L)
    n = periodic_noise(L, 1800, 9000, 0.0, seed=9)
    env = np.minimum(1.0, t / 0.006) * (np.exp(-t / 0.35) * 0.9 + 0.1 * np.exp(-((t - 0.45) / 0.08) ** 2))
    return fade(n * env, 0.0, 0.1)


def _syllable(f0, f1, f2, seconds, rng):
    n = int(seconds * RATE)
    t = np.arange(n) / RATE
    vib = f0 * (1 + 0.04 * np.sin(2 * np.pi * 5 * t + rng.uniform(0, 6)))
    ph = 2 * np.pi * np.cumsum(vib) / RATE
    out = np.zeros(n)
    for h in range(1, 30):
        hz = f0 * h
        if hz > 3500:
            break
        g = np.exp(-((hz - f1) / 160.0) ** 2) + 0.7 * np.exp(-((hz - f2) / 260.0) ** 2) + 0.05 / h
        out += g * np.sin(h * ph)
    return out * np.hanning(n)


def bed_market():
    """A crowd's murmur with no words: overlapping voiced syllables, a low roll of street noise, the odd cart bell."""
    L = 12.0
    rng = np.random.default_rng(21)
    buf = np.zeros(int(L * RATE))
    for _ in range(95):
        f0 = rng.choice([105, 120, 140, 190, 220, 260]) * rng.uniform(0.95, 1.05)
        syl = _syllable(f0, rng.uniform(300, 750), rng.uniform(900, 2300), rng.uniform(0.09, 0.26), rng) * rng.uniform(0.25, 1.0)
        circular_add(buf, int(rng.uniform(0, L) * RATE), syl)
    buf = buf / np.abs(buf).max()
    street = periodic_noise(L, 60, 900, 0.8, seed=4)
    out = buf * 0.9 + street * 0.35
    for _ in range(3):
        bell = resonant_hit([2350, 3100], [0.22, 0.15], [1.0, 0.5], 0.8, seed=5)
        circular_add(out, int(rng.uniform(0, L) * RATE), bell * 0.18)
    return out


def bed_tea():
    """A tea stall: boiling hiss, steel tumblers clinking, pouring, low talk."""
    L = 10.0
    rng = np.random.default_rng(33)
    t = t_axis(L)
    hiss = periodic_noise(L, 2500, 8000, 0.0, seed=2) * (0.25 + 0.2 * np.sin(2 * np.pi * 0.3 * t))
    boil = periodic_noise(L, 120, 700, 0.5, seed=6) * 0.6 * (0.5 + 0.5 * np.abs(np.sin(2 * np.pi * 1.7 * t)))
    out = hiss + boil
    for _ in range(11):
        base = rng.uniform(2300, 3400)
        clink = resonant_hit([base, base * 1.51, base * 2.21], [0.07, 0.05, 0.03], [1.0, 0.6, 0.35], 0.4, seed=int(rng.integers(999)))
        circular_add(out, int(rng.uniform(0, L) * RATE), clink * rng.uniform(0.25, 0.7))
    talk = np.zeros(len(t))
    for _ in range(26):
        syl = _syllable(rng.choice([110, 130, 200]) * rng.uniform(0.95, 1.05), rng.uniform(350, 700), rng.uniform(1000, 2000), rng.uniform(0.1, 0.24), rng)
        circular_add(talk, int(rng.uniform(0, L) * RATE), syl)
    out += 0.3 * talk / max(1e-9, np.abs(talk).max())
    return out


SOUNDS = {
    "rail.announce": dict(fn=rail_announce, loop=False, category="rail", what="Station announcement chime (synthetic)"),
    "rail.squeal": dict(fn=rail_squeal, loop=True, category="rail", what="Brake squeal loop (synthetic)"),
    "rail.clatter": dict(fn=rail_clatter, loop=True, category="rail", what="Wheel clatter over rail joints, loop at about 20 m/s (synthetic)"),
    "rail.rumble": dict(fn=rail_rumble, loop=True, category="rail", what="Train rumble and motor drone, loop (synthetic)"),
    "bus.airbrake": dict(fn=bus_airbrake, loop=False, category="vehicle", what="Bus air-brake hiss (synthetic)"),
    "bed.market": dict(fn=bed_market, loop=True, category="ambience", what="Market crowd murmur loop, no words (synthetic)"),
    "bed.tea": dict(fn=bed_tea, loop=True, category="ambience", what="Tea stall: boiling, tumblers, pouring, loop (synthetic)"),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    args = ap.parse_args()
    manifest = json.load(open(MANIFEST))
    files = manifest["files"]
    os.makedirs(os.path.join(ROOT, OUT), exist_ok=True)
    for pid, s in SOUNDS.items():
        if args.only and pid != args.only:
            continue
        x = np.asarray(s["fn"](), dtype=np.float64)
        x = x - x.mean()
        y, flag = normalise(x.astype(np.float32))
        rel = "%s/%s.ogg" % (OUT, pid.replace(".", "_"))
        dsp.write_ogg(os.path.join(ROOT, rel), y)
        files[pid] = {"path": "res://" + rel, "loop": s["loop"], "what": s["what"], "source": "synth", "licence": "CC0-1.0",
                      "author": AUTHOR, "url": "", "original": "", "edits": "Synthesised by tools/audio/synth_extras.py (no recording found), normalised to -16 LUFS (peak at most -2.2 dBFS)",
                      "rms": round(dsp.rms(y), 5), "seconds": round(len(y) / dsp.RATE, 3), "category": s["category"], "kind": "",
                      "normalised": "-16 LUFS" + (", peak limited" if flag else "")}
        files[pid]["metrics"] = dsp.measure(os.path.join(ROOT, rel))
        print("%-16s %.2f s %s" % (pid, len(y) / RATE, files[pid]["metrics"]))
    manifest["files"] = dict(sorted(files.items()))
    with open(MANIFEST, "w") as f:
        f.write(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    write_licences(manifest["files"])


def write_licences(files):
    lines = [BEGIN, "| Files | What | Source | Licence |", "|---|---|---|---|"]
    for pid, row in sorted(files.items()):
        if row["path"].startswith("res://" + OUT):
            lines.append("| `%s` | %s (`%s`) | Original, synthesised by `tools/audio/synth_extras.py` (no recording found; **synthetic**) | **CC0-1.0**, original work for the project |" % (
                row["path"].replace("res://", ""), row["what"], pid))
    lines.append(END)
    text = open(LICENSES).read()
    block = "\n".join(lines)
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text = text.replace("<!-- audio_recordings:begin", block + "\n\n<!-- audio_recordings:begin", 1)
    open(LICENSES, "w").write(text)


if __name__ == "__main__":
    main()
