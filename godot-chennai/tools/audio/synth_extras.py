#!/usr/bin/env python3
"""Procedural sounds for what no free recording could be found for (decision G-372).

    python3 tools/audio/synth_extras.py [--only rail.squeal]

Writes OGG Vorbis (mono, 22.05 kHz) into `assets/audio/synthetic/`, the manifest rows (source
"synth", licence CC0-1.0, the author named as this script) and nothing in LICENSES.md by hand: the
rows between the `audio_synthetic` markers are written here. Deterministic (fixed seeds). Every sound
is built so that a loop wraps without a click: noise is made in the frequency domain (periodic by
construction), oscillators use whole cycles per loop, hits are added into a circular buffer.

These are SYNTHETIC. They are marked `"source": "synth"` in the manifest and are the first thing to
replace with a phone recording (see docs/sound-recordings.md for what to record).
"""
import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audio_dsp as dsp  # noqa: E402
import tempfile  # noqa: E402

RATE = dsp.RATE
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = "assets/audio/synthetic"
MANIFEST = os.path.join(ROOT, "assets", "audio", "manifest.json")
LICENSES = os.path.join(ROOT, "assets", "LICENSES.md")
BEGIN = "<!-- audio_synthetic:begin (generated by tools/audio/synth_extras.py) -->"
END = "<!-- audio_synthetic:end -->"
AUTHOR = "Chennai Open World project (synthesised by tools/audio/synth_extras.py)"


def t_axis(seconds):
    return np.arange(int(round(seconds * RATE))) / RATE


def normalise(y, target_lufs=-16.0, peak=0.78):
    """Gain to `target_lufs` (BS.1770 integrated loudness), but never past `peak` (linear; 0.78 is
    -2.2 dBFS, so the decoded Ogg stays under -1 dBFS). Returns (samples, flag) where flag is
    "peak_limited" when the peak, not the loudness, set the gain."""
    with tempfile.TemporaryDirectory() as d:
        tmp = os.path.join(d, "n.wav")
        dsp.write_wav(tmp, y)
        now = dsp.lufs(tmp)
    g = 10 ** ((target_lufs - now) / 20)
    top = float(np.max(np.abs(y)))
    limited = g * top > peak
    if limited:
        g = peak / top
    return (y * g).astype(np.float32), "peak_limited" if limited else ""


def periodic_noise(seconds, lo, hi, slope=0.0, seed=1):
    """Noise whose spectrum is flat (slope 0) or 1/f^slope between lo and hi Hz, periodic over
    `seconds` (so it loops seamlessly)."""
    rng = np.random.default_rng(seed)
    n = int(round(seconds * RATE))
    freqs = np.fft.rfftfreq(n, 1 / RATE)
    mag = np.zeros(len(freqs))
    band = (freqs >= lo) & (freqs <= hi)
    mag[band] = 1.0 / np.maximum(freqs[band], 1.0) ** slope
    spec = mag * np.exp(1j * rng.uniform(0, 2 * np.pi, len(freqs)))
    x = np.fft.irfft(spec, n)
    return x / max(1e-9, np.abs(x).max())


def circular_add(buf, start, hit):
    n = len(buf)
    idx = (start + np.arange(len(hit))) % n
    np.add.at(buf, idx, hit)


def resonant_hit(freqs, decays, amps, seconds=0.25, seed=0):
    t = np.arange(int(seconds * RATE)) / RATE
    rng = np.random.default_rng(seed)
    out = np.zeros_like(t)
    for f, d, a in zip(freqs, decays, amps):
        out += a * np.sin(2 * np.pi * f * t + rng.uniform(0, 6)) * np.exp(-t / d)
    out += 0.3 * rng.standard_normal(len(t)) * np.exp(-t / 0.004)
    return out * np.minimum(1.0, t / 0.0008)


def fade(x, a=0.004, b=0.05):
    x = x.copy()
    na, nb = int(a * RATE), int(b * RATE)
    if na:
        x[:na] *= np.linspace(0, 1, na)
    if nb:
        x[-nb:] *= np.linspace(1, 0, nb)
    return x


