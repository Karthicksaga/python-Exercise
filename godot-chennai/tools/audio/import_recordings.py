#!/usr/bin/env python3
"""Turns licensed recordings into the game's sound files (decision G-85).

    python3 tools/audio/import_recordings.py --cache <download dir> [--only engine.car]

Reads `tools/audio/recordings.json`: for each recording, its Wikimedia Commons file title and the
pieces cut from it (engine loops at measured rpm, one-shots, beds). For each piece it decodes the
recording (ffmpeg), cuts the segment, and:
- engine loops: measures the firing note in the segment, cuts a whole number of firing periods
  with a crossfaded wrap (so the loop repeats on the beat and pitch-shifting keeps time), stores
  the measured rpm (firing Hz x 60 / (cylinders / 2)) and writes 16-bit mono WAV;
- other loops: crossfaded wrap, OGG Vorbis; one-shots: short fades, OGG Vorbis;
- loudness: every piece is matched to the RMS of the stand-in it replaces (the mix was tuned on
  the stand-ins, `tests/unit/test_sound_mix.gd`), peaks kept under -1 dBFS.
Then it writes the manifest rows (source URL, author, licence, original file, edits, measured rms)
and the licence rows between the markers in `assets/LICENSES.md`. A kind with recorded engine loops
loses all its synthesised loops (never a mix of the two).

Downloads: the recordings are fetched by hand or by `fetch_commons.py` into the cache directory
(Wikimedia rate-limits; respect Retry-After). Only CC0, public domain and CC-BY are accepted.
"""
import argparse
import html
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audio_dsp as dsp  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MANIFEST = os.path.join(ROOT, "assets", "audio", "manifest.json")
LICENSES = os.path.join(ROOT, "assets", "LICENSES.md")
SPEC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "recordings.json")
OUT_DIR = "assets/audio/rec"
BEGIN = "<!-- audio_recordings:begin (generated by tools/audio/import_recordings.py) -->"
END = "<!-- audio_recordings:end -->"
CYLINDERS = {"car": 4, "premium": 8, "race": 4, "auto": 1, "bike": 1, "thumper": 1, "bus": 6, "ambulance": 4}


def licence_id(short):
    s = short.strip()
    if s in ("CC0", "CC0 1.0"):
        return "CC0-1.0"
    if s.lower() in ("public domain", "pd"):
        return "Public domain"
    m = re.match(r"CC BY (\d\.\d)\s*(\w*)$", s)
    if m:
        return "CC-BY-" + m.group(1) + ("-" + m.group(2) if m.group(2) else "")
    raise SystemExit("refused licence %r" % short)


def plain(text):
    return html.unescape(re.sub(r"<[^>]+>", "", text or "")).strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", required=True)
    ap.add_argument("--only", default="")
    args = ap.parse_args()
    spec = json.load(open(SPEC))
    meta = {}
    for name in sorted(os.listdir(args.cache)):
        if name.startswith("meta") and name.endswith(".json"):
            meta.update(json.load(open(os.path.join(args.cache, name))))
    manifest = json.load(open(MANIFEST))
    files = manifest["files"]
    os.makedirs(os.path.join(ROOT, OUT_DIR), exist_ok=True)
    rows = {}
    recorded_kinds = set()
    for rec in spec["recordings"]:
        m = meta.get(rec["title"])
        if not m or not os.path.exists(m["local"] if os.path.isabs(m["local"]) else os.path.join(args.cache, os.path.relpath(m["local"], "dl"))):
            print("skip (not downloaded):", rec["title"])
            continue
        lic = licence_id(m["licence"])
        author = plain(m.get("artist")) or "unknown"
        local = m["local"] if os.path.isabs(m["local"]) else os.path.join(args.cache, os.path.relpath(m["local"], "dl"))
        x = dsp.decode(local)
        for piece in rec["pieces"]:
            pid = piece["id"]
            if args.only and not pid.startswith(args.only):
                continue
            stand_in = files.get(pid, {})
            target = float(piece.get("rms", stand_in.get("rms", 0.05)))
            base = os.path.join(OUT_DIR, pid.replace(".", "_"))
            row = {"category": piece.get("category", stand_in.get("category", "")), "loop": bool(piece.get("loop", False)),
                   "what": piece.get("what", ""), "source": "recording", "licence": lic, "author": author,
                   "url": m["url"], "original": m.get("original") or m["file_url"].split("?")[0].rsplit("/", 1)[1], "kind": piece.get("kind", stand_in.get("kind", ""))}
            if pid.startswith("engine.") and ".loop." in pid:
                kind = pid.split(".")[1]
                recorded_kinds.add(kind)
                seg = x[int(piece["start"] * dsp.RATE):int((piece["start"] + piece["length"] + 0.1) * dsp.RATE)]
                hz = dsp.firing_hz(dsp.lowpass(seg, piece.get("lowpass", 400)), piece["hz"][0], piece["hz"][1])
                y, hz = dsp.loop(x, piece["start"], piece["length"], hz)
                rpm = hz * 60 / (CYLINDERS[kind] / 2)
                y = dsp.match_rms(y, target)
                dsp.write_wav(os.path.join(ROOT, base + ".wav"), y)
                row.update({"path": "res://%s.wav" % base, "loop": True, "rpm": round(rpm, 3), "load": piece.get("load", "off"),
                            "edits": "Cut %.2f-%.2f s, %d whole firing periods at %.2f Hz (measured), crossfaded wrap, mono 22.05 kHz, RMS matched to the stand-in" % (piece["start"], piece["start"] + len(y) / dsp.RATE, round(len(y) * hz / dsp.RATE), hz)})
            elif piece.get("loop"):
                y = dsp.loop(x, piece["start"], piece["length"], 4.0 / piece["length"], fade=0.25)[0]
                y = dsp.match_rms(y, target)
                dsp.write_ogg(os.path.join(ROOT, base + ".ogg"), y)
                row.update({"path": "res://%s.ogg" % base, "edits": "Cut %.2f s from %.2f s, crossfaded wrap, mono 22.05 kHz, RMS matched, OGG Vorbis q3" % (piece["length"], piece["start"])})
            else:
                y = dsp.one_shot(x, piece["start"], piece["length"], fade_out=piece.get("fade_out", 0.05))
                y = dsp.match_rms(y, target)
                dsp.write_ogg(os.path.join(ROOT, base + ".ogg"), y)
                row.update({"path": "res://%s.ogg" % base, "edits": "Cut %.2f-%.2f s, fades, mono 22.05 kHz, RMS matched, OGG Vorbis q3" % (piece["start"], piece["start"] + piece["length"])})
            if stand_in.get("source") == "synth" and stand_in.get("path") != row["path"]:
                old = os.path.join(ROOT, stand_in["path"].replace("res://", ""))
                for p in (old, old + ".import"):
                    if os.path.exists(p):
                        os.remove(p)
            row["rms"] = round(dsp.rms(y), 5)
            row["seconds"] = round(len(y) / dsp.RATE, 3)
            files[pid] = row
            rows.setdefault(rec["title"], []).append((row["path"].replace("res://", ""), pid, lic, author, m["url"], row["original"]))
            print("%-28s %s %s" % (pid, row.get("rpm", ""), row["path"]))
    # A kind with recorded engine loops plays only recordings: drop its synthesised loops.
    for pid in list(files):
        parts = pid.split(".")
        if pid.startswith("engine.") and ".loop." in pid and parts[1] in recorded_kinds and files[pid].get("source") == "synth":
            path = os.path.join(ROOT, files[pid]["path"].replace("res://", ""))
            for p in (path, path + ".import"):
                if os.path.exists(p):
                    os.remove(p)
            del files[pid]
    manifest["files"] = dict(sorted(files.items()))
    with open(MANIFEST, "w") as f:
        f.write(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    write_licences(files)


def write_licences(files):
    lines = [BEGIN, "| Files | What | Source | Licence |", "|---|---|---|---|"]
    for pid, row in sorted(files.items()):
        if row.get("source") != "recording":
            continue
        rel = row["path"].replace("res://", "")
        site = "OpenGameArt" if "opengameart.org" in row["url"] else "Wikimedia Commons"
        lines.append("| `%s` | %s (`%s`) | %s, by %s, from %s (%s); edited: %s | **%s** |" % (
            rel, row.get("what") or pid, pid, row["original"], row["author"], site, row["url"], row["edits"], row["licence"]))
    lines.append(END)
    text = open(LICENSES).read()
    block = "\n".join(lines)
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    open(LICENSES, "w").write(text)


if __name__ == "__main__":
    main()
