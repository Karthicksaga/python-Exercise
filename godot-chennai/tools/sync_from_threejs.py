def pairs() -> list[tuple[Path, Path]]:
    """(source, destination) for every managed file, sorted, failing if a set is empty."""
    out: list[tuple[Path, Path]] = []
    for s in SETS:
        root = OLD / s.source
        found = sorted({p for pattern in s.patterns for p in root.glob(pattern) if p.is_file()})
        if not found:
            sys.exit(f"sync: nothing matches {s.patterns} in {root}")
        out += [(p, GODOT / s.target / p.relative_to(root)) for p in found]
    return out


def licence_block() -> str:
    rows = ["| Files | What | Source | Licence |", "|---|---|---|---|"]
    for s in SETS:
        files = ", ".join(f"`{s.target}/{p}`" for p in s.patterns)
        rows.append(f"| {files} | {s.what} | {s.origin} | {s.licence} |")
    return "\n".join([BEGIN, *rows, END])


def licences_text(current: str) -> str:
    block = licence_block()
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        return head + block + rest.split(END, 1)[1]
    return current.rstrip("\n") + "\n\n" + block + "\n"


def stale(managed: list[tuple[Path, Path]]) -> list[Path]:
    """Files in a synced folder that no longer exist in the old game (only for globbed sets)."""
    wanted = {d for _, d in managed}
    out: list[Path] = []
    for s in SETS:
        for pattern in s.patterns:
            if "*" not in pattern:
                continue
            for p in (GODOT / s.target).glob(pattern):
                if p.is_file() and p not in wanted:
                    out.append(p)
    return sorted(set(out))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift and exit 1 instead of copying")
    args = parser.parse_args()
    if not OLD.is_dir():
        sys.exit(f"sync: {OLD} not found")
    managed = pairs()
    current = LICENSES.read_text(encoding="utf-8") if LICENSES.exists() else "# Asset licences\n"
    wanted_licences = licences_text(current)
    if args.check:
        drift = [str(d.relative_to(GODOT)) for s, d in managed if not d.exists() or not filecmp.cmp(s, d, shallow=False)]
        extra = [str(p.relative_to(GODOT)) for p in stale(managed)]
        bad = False
        if drift:
            bad = True
            print(f"sync --check: {len(drift)} file(s) missing or different, e.g. {drift[:5]}")
        if extra:
            bad = True
            print(f"sync --check: {len(extra)} file(s) no longer in chennai-open-world, e.g. {extra[:5]}")
        if wanted_licences != current:
            bad = True
            print("sync --check: assets/LICENSES.md rows are out of date")
        if bad:
            print("Run python3 godot-chennai/tools/sync_from_threejs.py and commit the result.")
            return 1
        print(f"sync --check: {len(managed)} files match chennai-open-world")
        return 0
    copied = 0
    for src, dst in managed:
        if dst.exists() and filecmp.cmp(src, dst, shallow=False):
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        copied += 1
    removed = stale(managed)
    for p in removed:
        p.unlink()
        sidecar = p.with_name(p.name + ".import")
        if sidecar.exists():
            sidecar.unlink()
    LICENSES.parent.mkdir(parents=True, exist_ok=True)
    LICENSES.write_text(wanted_licences, encoding="utf-8")
    print(f"sync: {len(managed)} files managed, {copied} copied, {len(removed)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
