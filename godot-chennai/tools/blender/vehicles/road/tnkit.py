"""
Shared parts for the Tamil Nadu road vehicles (autos, Indian cars, buses, the van ambulance),
on top of `vkit.py` (palette atlas, LODs, anchors, export). Blender 5.2 LTS, by script.

The scripts that use it (`autos.py`, `cars_in.py`, `buses.py`) are the source of the models in
`assets/vehicles/`. Every design is original and modelled by script at the real proportions of
its class. Photographs of real Tamil Nadu vehicles (Wikimedia Commons, listed in
`docs/vehicles.md`) were looked at for proportions, part layout and colour families only: none is
in the repository, none is used as a texture, and no badge, maker's name, grille shape, operator
name, emblem, lettering or real registration is reproduced (G-90, G-91).

Frame and materials as `vkit.py`: Blender Z up, front +Y, ground z = 0; exported +Y up with the
front towards -Z. Fixed colours are palette cells, the body colour is the `paint` material
(recoloured from the manifest), buses carry one painted livery each (`livery_<name>`).
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import vkit as K  # noqa: E402
from vkit import Matrix, Vector, role  # noqa: E402

OUT = os.path.join(K.ROOT, "assets", "vehicles")
SETTLED = 0.3  # settled suspension of the old game's VehicleSpec (specs.ts)

LICENCE = ("Original work for this project, generated by the script named in `source` with Blender 5.2 LTS. "
           "Modelled from real proportions of the vehicle class; reference photographs (Wikimedia Commons, listed in "
           "docs/vehicles.md) were looked at, not used as textures or traced, and are not shipped. No make, badge, "
           "maker's name, grille shape, operator name or emblem, lettering or real registration.")


def lod_name(name, lod):
    return name + ("" if lod == 0 else f"_lod{lod}")


# ----------------------------------------------------------------------------- wheels


def steel_wheel(name, location, radius, width, rim_r, rim_role="steel", studs=4, dual=False, face_sign=None, hubcap=None):
    """A tyre on a pressed-steel (or painted) disc rim with a hub and studs; `dual` adds a second
    tyre inboard (bus and lorry rear axles). Origin on the axle, spinning about X."""
    sx = face_sign if face_sign is not None else (1 if location[0] >= 0 else -1)
    hw = width / 2
    sidewall = 1 - rim_r / radius
    segs = K.seg(24, 14, 8)
    parts = []
    offsets = [0.0] if not dual else [0.0, -width * 1.06]
    for off in offsets:
        t = K.tyre(radius, width, role("rubber"), sidewall=sidewall, segments=segs)
        t.location.x = off
        parts.append(t)
    face = hw * 0.7
    if K.LOD == 0:
        # Dish: rim lip, the dished face, the centre with the hub.
        parts.append(K.lathe("rim", [(rim_r + 0.008, face), (rim_r - 0.01, face - 0.01), (rim_r * 0.72, face - 0.035),
                                     (rim_r * 0.42, face - 0.03), (rim_r * 0.3, face - 0.012), (0.0001, face - 0.012)],
                             role(rim_role), K.seg(20, 12)))
        parts.append(K.lathe("hub", [(rim_r * 0.26, face - 0.01), (rim_r * 0.2, face + 0.035), (0.0001, face + 0.04)],
                             role(hubcap or "dark_alloy"), 10))
        for i in range(studs):
            a = 2 * math.pi * i / studs
            parts.append(K.cylinder("stud", 0.012, 0.03, (face, math.cos(a) * rim_r * 0.36, math.sin(a) * rim_r * 0.36),
                                    role("chrome"), rot=(0, math.pi / 2, 0), verts=6))
        # Ventilation holes as dark dots on the dish.
        for i in range(6 if radius > 0.4 else 4):
            a = 2 * math.pi * (i + 0.5) / (6 if radius > 0.4 else 4)
            parts.append(K.cylinder("vent", rim_r * 0.1, 0.006, (face - 0.028, math.cos(a) * rim_r * 0.58, math.sin(a) * rim_r * 0.58),
                                    role("inside_dark"), rot=(0, math.pi / 2, 0), verts=8))
    else:
        parts.append(K.lathe("rim", [(rim_r + 0.006, face), (rim_r * 0.4, face - 0.02), (0.0001, face - 0.005)],
                             role(rim_role), K.seg(16, 8, 6)))
    w = K.join(parts, name)
    if sx < 0:
        w.data.transform(Matrix.Scale(-1, 4, (1, 0, 0)))
        w.data.flip_normals()
    for p in w.data.polygons:
        p.use_smooth = True
    w.location = location
    return w


# ----------------------------------------------------------------------------- small fittings


def plate(centre, normal_y, width=0.34, height=0.11, commercial=True):
    """A blank number plate (the game draws an invented number): yellow for commercial
    vehicles (autos, taxis, buses, goods), white for private cars, as in India."""
    return K.box("plate", (width, 0.012, height), centre, role("yellow" if commercial else "plate"))


def mirror_on_stalk(base, sx, reach=0.18, up=0.16, size=(0.13, 0.03, 0.09), mat=None):
    """A round-ish mirror head on a thin stalk (autos, buses, goods carriers)."""
    b = Vector(base)
    head = b + Vector((sx * reach, 0.02, up))
    parts = [K.tube("stalk", b, head, 0.009, role("black"), verts=K.seg(6, 4)),
             K.box("mirror", size, head, mat or role("black"), bevel=0.02)]
    if K.LOD == 0:
        parts.append(K.box("mirror_glass", (size[0] * 0.85, 0.006, size[2] * 0.8), head + Vector((0, -size[1] / 2 - 0.002, 0)), role("chrome")))
    return parts


def lamp_disc(centre, radius, normal, lamp_role="headlamp", rim_role="chrome", depth=0.04):
    """A round lamp: a chrome ring and the lens, facing `normal` (Blender frame)."""
    n = Vector(normal).normalized()
    q = Vector((0, 0, 1)).rotation_difference(n)
    c = Vector(centre)
    ring = K.cylinder("lamp_ring", radius * 1.18, depth, c, role(rim_role), verts=K.seg(20, 10, 6))
    ring.rotation_mode = "QUATERNION"
    ring.rotation_quaternion = q
    lens = K.cylinder("lamp_lens", radius, depth, c + n * 0.006, role(lamp_role), verts=K.seg(20, 10, 6))
    lens.rotation_mode = "QUATERNION"
    lens.rotation_quaternion = q
    return [ring, lens]


def rounded_rect(y, hw, zb, zt, rb, rt, n_arc=3, crown=0.0):
    """A cross-section ring (Blender frame) at y: half width hw, from zb to zt, bottom corner
    radius rb, top corner radius rt and a roof crown (bus and van bodies, auto tubs)."""
    pts = []

    def arc(cx, cz, r, a0, a1, k):
        return [(cx + r * math.cos(a0 + (a1 - a0) * i / k), cz + r * math.sin(a0 + (a1 - a0) * i / k)) for i in range(k + 1)]

    k = max(1, n_arc)
    # Bottom right corner, up the right side, top right corner, across the roof, down the left.
    pts += arc(hw - rb, zb + rb, rb, -math.pi / 2, 0, k)
    pts += arc(hw - rt, zt - rt, rt, 0, math.pi / 2, k)
    if crown > 0:
        for i in range(1, 4):
            x = (hw - rt) * (1 - i / 2.0)
            pts.append((x, zt + crown * (1 - (x / (hw - rt)) ** 2)))
    pts += arc(-(hw - rt), zt - rt, rt, math.pi / 2, math.pi, k)
    pts += arc(-(hw - rb), zb + rb, rb, math.pi, 1.5 * math.pi, k)
    out = []
    for x, z in pts:
        p = Vector((x, y, z))
        if not out or (p - out[-1]).length > 1e-5:
            out.append(p)
    if (out[0] - out[-1]).length < 1e-5:
        out.pop()
    return out


# ----------------------------------------------------------------------------- livery UVs


def project_livery(obj, mat_name, y0, y1, half_w, height):
    """Planar UVs for the faces of material `mat_name` on a box-like body (buses):
    the sides (both share the art, front to the right) fill v 0.375-1 with u along the length and
    v up the height; the front face fills u 0-0.5 and the rear u 0.5-1 of v 0-0.375. Roof faces read
    the top row of the side strip, so the painter puts the roof colour there."""
    me = obj.data
    idx = None
    for i, m in enumerate(me.materials):
        if m is not None and m.name == mat_name:
            idx = i
    if idx is None:
        return
    if not me.uv_layers:
        me.uv_layers.new(name="UVMap")
    uv = me.uv_layers[0].data
    L = y1 - y0
    for p in me.polygons:
        if p.material_index != idx:
            continue
        n = p.normal
        ax, ay, az = abs(n.x), abs(n.y), abs(n.z)
        for li in p.loop_indices:
            v = obj.matrix_world @ me.vertices[me.loops[li].vertex_index].co
            if az > max(ax, ay) and n.z > 0:
                uu, vv = (v.y - y0) / L, 0.995
            elif ay > ax and ay >= az:
                xx = min(max((v.x / (2 * half_w)) + 0.5, 0.002), 0.998)
                zz = min(max(v.z / height, 0.002), 0.998)
                # Seen from outside: on the front the viewer's right is -x, on the rear +x.
                uu = 0.5 * (1 - xx) if n.y > 0 else 0.5 + 0.5 * xx
                vv = 0.375 * zz
            else:
                uu = (v.y - y0) / L
                vv = 0.375 + 0.625 * min(max(v.z / height, 0.002), 0.998)
            uv[li].uv = (min(max(uu, 0.001), 0.999), vv)


# ----------------------------------------------------------------------------- manifests


def physics_block(mass, ride, wheels_bl, ph):
    """VehicleSpec-shaped handling (`packages/vehicles/src/specs.ts`), chassis frame: wheel y =
    radius + settled suspension 0.3 - ride height so `groundBelow` works unchanged."""
    ph = dict(ph)
    gears = ph.pop("gears")
    wheels = [dict(x=round(x, 3), y=round(r + SETTLED - ride, 3), z=round(-y, 3), radius=r, steers=s, driven=d)
              for _n, x, y, r, s, d in wheels_bl]
    return dict(mass=mass, wheels=wheels, gears=gears, rideHeight=ride, **ph)


def chassis_up(wheels_bl, ride):
    """y_model = y_chassis + up (the old game's groundBelow): up = ride height."""
    return ride


def write(name, data):
    K.write_manifest(os.path.join(OUT, name + ".json"), data)


def base_manifest(name, label, kind, source, results, wheels_bl, mass, lod_ranges):
    lo, hi = results[0]["lo"], results[0]["hi"]
    lods = []
    for i, r in enumerate(results):
        e = dict(file=lod_name(name, i) + ".glb", triangles=r["tris"])
        a, b = lod_ranges[i]
        if a:
            e["min_distance_m"] = a
        e["max_distance_m"] = b
        lods.append(e)
    wheels = []
    for nm, x, y, r, s, d in wheels_bl:
        w = dict(node=nm, centre=K.g((x, y, r)), radius=r, steers=s, driven=d)
        if len(results) > 2:
            w["lod_max"] = 1
        wheels.append(w)
    return dict(
        name=name, label=label, kind=kind, source=source, licence=LICENCE,
        frame="metres; +Y up, front faces -Z, +X right; ground at y = 0; origin centred between the axles",
        size_m=dict(zip(("width", "height", "length"), K.size_godot(lo, hi))),
        mass_kg=mass, lods=lods, wheels=wheels,
    )


def export(name, lod):
    lo, hi = K.scene_bounds()
    tris = K.export_glb(os.path.join(OUT, lod_name(name, lod) + ".glb"))
    return dict(tris=tris, lo=lo, hi=hi)
