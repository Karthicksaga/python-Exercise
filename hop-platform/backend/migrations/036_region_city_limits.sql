-- City limits for catalogue districts (Nov 2026 admin redesign).
-- The console's "City limits" button shrinks a district-sized zone to the city in one click,
-- so operators rarely type coordinates. Reference data only: nothing changes existing zones.
-- city_source: 'boundary' = OpenStreetMap city/town boundary; 'approx' = a box around the city
-- centre where OSM has no boundary (the console labels it as approximate).

ALTER TABLE region_catalog
  ADD COLUMN city text CHECK (city IS NULL OR length(city) BETWEEN 2 AND 100),
  ADD COLUMN city_source text CHECK (city_source IS NULL OR city_source IN ('boundary', 'approx')),
  ADD COLUMN city_min_lat double precision, ADD COLUMN city_max_lat double precision,
  ADD COLUMN city_min_lng double precision, ADD COLUMN city_max_lng double precision,
  ADD CONSTRAINT region_catalog_city_box CHECK (
    (city_min_lat IS NULL AND city_max_lat IS NULL AND city_min_lng IS NULL AND city_max_lng IS NULL AND city_source IS NULL)
    OR (city_min_lat < city_max_lat AND city_min_lng < city_max_lng AND city_source IS NOT NULL
        AND city_min_lat >= min_lat AND city_max_lat <= max_lat AND city_min_lng >= min_lng AND city_max_lng <= max_lng));

