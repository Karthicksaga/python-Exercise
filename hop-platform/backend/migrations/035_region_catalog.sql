-- District catalogue: an operator picks a district to start a new service zone instead of typing
-- coordinates. A catalogue entry is reference data only; zones still start inactive and need fares
-- and an approval reference before going live (see areas CHECK in 001). Each district maps to at most one zone.

CREATE TABLE region_catalog (
  id text PRIMARY KEY CHECK (id ~ '^[a-z]{2}-[a-z0-9-]{2,60}$'),
  country text NOT NULL DEFAULT 'IN' CHECK (country = 'IN'),
  state text NOT NULL CHECK (length(state) BETWEEN 2 AND 100),
  district text NOT NULL CHECK (length(district) BETWEEN 2 AND 100),
  osm_relation bigint,
  lgd_code text CHECK (lgd_code IS NULL OR lgd_code ~ '^[0-9]{1,8}$'),
  min_lat double precision NOT NULL, max_lat double precision NOT NULL,
  min_lng double precision NOT NULL, max_lng double precision NOT NULL,
  centre_lat double precision NOT NULL, centre_lng double precision NOT NULL,
  source text NOT NULL DEFAULT 'OpenStreetMap contributors (ODbL 1.0)',
  CHECK (min_lat >= 6 AND max_lat <= 38 AND min_lat < max_lat AND min_lng >= 68 AND max_lng <= 98 AND min_lng < max_lng),
  CHECK (centre_lat BETWEEN min_lat AND max_lat AND centre_lng BETWEEN min_lng AND max_lng),
  UNIQUE (state, district)
);

ALTER TABLE areas ADD COLUMN catalog_id text UNIQUE REFERENCES region_catalog(id);

