"""Build a district catalogue migration for one Indian state from OpenStreetMap (Nominatim).

Run once by a developer, review the output and commit it as a migration. The API never calls
OpenStreetMap at runtime. Data is (c) OpenStreetMap contributors, ODbL 1.0.

Usage:
  python3 -I scripts/fetch_districts.py "Tamil Nadu" tn scripts/districts/tamil_nadu.txt > districts.json
  python3 -I scripts/fetch_districts.py --sql 35 districts.json > migrations/035_x.sql

The names file has one district per line. Alternate OpenStreetMap spellings follow a "|":
  Tiruvallur|Thiruvallur
Official district names and LGD codes: https://lgdirectory.gov.in (Local Government Directory).

City limits (the box the console's "City limits" button uses) come from a second run:
  python3 -I scripts/fetch_districts.py --cities "Tamil Nadu" tn scripts/districts/tamil_nadu.txt > cities.json
  python3 -I scripts/fetch_districts.py --city-sql 36 cities.json > migrations/036_x.sql

The city is the district's headquarters town, named like the district unless the names file
gives it after a ">" (alternate spellings again after "|"):
  Nilgiris > Udhagamandalam|Ooty
The OSM city or town boundary is used when it exists. Otherwise the box is drawn around the city
centre (city_source 'approx') and the console labels it as approximate.
"""

import json
import re
import sys
import time
import urllib.parse
import urllib.request

AGENT = "hop-district-import/1.0 (developer tool; run rarely)"


def lookup(query, state):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(
        {"q": f"{query}, {state}, India", "format": "jsonv2", "limit": 8})
    rows = json.load(urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": AGENT}), timeout=30))
    time.sleep(1.2)  # Nominatim usage policy: at most one request per second.
    return next((r for r in rows if r.get("osm_type") == "relation"
                 and r.get("addresstype") in ("state_district", "district") and state in r["display_name"]), None)


def parse(line):
    district, _, city = line.partition(">")
    return [n.strip() for n in district.split("|") if n.strip()], [n.strip() for n in city.split("|") if n.strip()]


# Half-widths in degrees for the approximate box drawn around a city or town centre when
# OpenStreetMap has no boundary for it (about 15 km across for a city, 9 km for a town).
APPROX_HALF = {"city": 0.07, "town": 0.04}


def city_lookup(query, state):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(
        {"q": f"{query}, {state}, India", "format": "jsonv2", "limit": 8})
    rows = json.load(urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": AGENT}), timeout=30))
    time.sleep(1.2)
    rows = [r for r in rows if state in r["display_name"]]
    boundary = next((r for r in rows if r.get("osm_type") in ("relation", "way") and r.get("addresstype") in ("city", "town", "municipality")), None)
    if boundary:
        b = [float(x) for x in boundary["boundingbox"]]
        return b, "boundary"
    # A place node's bounding box is synthetic, so build a modest box around its centre instead.
    node = next((r for r in rows if r.get("osm_type") == "node" and r.get("type") in APPROX_HALF), None)
    if node:
        lat, lng, h = float(node["lat"]), float(node["lon"]), APPROX_HALF[node["type"]]
        return [lat - h, lat + h, lng - h, lng + h], "approx"
    return None


def fetch_cities(state, prefix, names_file):
    out, missing = [], []
    for line in open(names_file, encoding="utf-8"):
        names, cities = parse(line)
        if not names:
            continue
        pick = None
        for name in cities or names:
            pick = city_lookup(name, state)
            if pick:
                break
        if not pick:
            missing.append(names[0])
            continue
        b, source = pick
        out.append({"id": prefix + "-" + re.sub(r"[^a-z0-9]+", "-", names[0].lower()).strip("-"), "city": (cities or names)[0], "city_source": source,
                    "city_min_lat": round(b[0], 4), "city_max_lat": round(b[1], 4), "city_min_lng": round(b[2], 4), "city_max_lng": round(b[3], 4)})
    if missing:
        print("No city boundary found (left without city limits): " + ", ".join(missing), file=sys.stderr)
    json.dump(out, sys.stdout, indent=1)


def city_sql(version, path):
    rows = json.load(open(path, encoding="utf-8"))
    print(f"-- City limits for {len(rows)} catalogue districts: the box the console's \"City limits\" button applies.")
    print("-- Boundary boxes (c) OpenStreetMap contributors, ODbL 1.0. Generated by scripts/fetch_districts.py --cities.")
    print("-- A city box must sit inside its district box; rows that don't are skipped by the WHERE clause.")
    print("-- city_source: 'boundary' is the OSM city boundary; 'approx' is a box around the city centre (no boundary in OSM).")
    print("UPDATE region_catalog c SET city=v.city,city_source=v.src,city_min_lat=v.a,city_max_lat=v.b,city_min_lng=v.c,city_max_lng=v.d FROM (VALUES")
    values = [f"({sql_text(r['id'])},{sql_text(r['city'])},{sql_text(r['city_source'])},{r['city_min_lat']},{r['city_max_lat']},{r['city_min_lng']},{r['city_max_lng']})" for r in rows]
    print(",\n".join(values))
    print(") AS v(id,city,src,a,b,c,d) WHERE c.id=v.id AND v.a>=c.min_lat AND v.b<=c.max_lat AND v.c>=c.min_lng AND v.d<=c.max_lng;")


def fetch(state, prefix, names_file):
    out, missing = [], []
    for line in open(names_file, encoding="utf-8"):
        names, _ = parse(line)
        if not names:
            continue
        pick = None
        for name in names:
            pick = lookup(name + " district", state) or lookup(name, state)
            if pick:
                break
        if not pick:
            missing.append(names[0])
            continue
        b = [float(x) for x in pick["boundingbox"]]
        out.append({"id": prefix + "-" + re.sub(r"[^a-z0-9]+", "-", names[0].lower()).strip("-"),
                    "state": state, "district": names[0], "osm_relation": int(pick["osm_id"]),
                    "min_lat": round(b[0], 4), "max_lat": round(b[1], 4), "min_lng": round(b[2], 4), "max_lng": round(b[3], 4),
                    "centre_lat": round(float(pick["lat"]), 4), "centre_lng": round(float(pick["lon"]), 4)})
    if missing:
        sys.exit("Not found (add an alternate spelling): " + ", ".join(missing))
    json.dump(out, sys.stdout, indent=1)


def sql_text(s):
    return "'" + s.replace("'", "''") + "'"


def sql(version, path):
    rows = json.load(open(path, encoding="utf-8"))
    print(f"-- District catalogue: {rows[0]['state']} ({len(rows)} districts).")
    print("-- Boundary boxes (c) OpenStreetMap contributors, ODbL 1.0. Generated by scripts/fetch_districts.py.")
    print("INSERT INTO region_catalog(id,state,district,osm_relation,min_lat,max_lat,min_lng,max_lng,centre_lat,centre_lng) VALUES")
    values = [f"({sql_text(r['id'])},{sql_text(r['state'])},{sql_text(r['district'])},{r['osm_relation']},"
              f"{r['min_lat']},{r['max_lat']},{r['min_lng']},{r['max_lng']},{r['centre_lat']},{r['centre_lng']})" for r in rows]
    print(",\n".join(values))
    print("ON CONFLICT (id) DO NOTHING;")
    print(f"\nINSERT INTO schema_migrations(version) VALUES({int(version)});")


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "--sql":
        sql(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 4 and sys.argv[1] == "--city-sql":
        city_sql(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 5 and sys.argv[1] == "--cities":
        fetch_cities(sys.argv[2], sys.argv[3], sys.argv[4])
    elif len(sys.argv) == 4:
        fetch(sys.argv[1], sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
